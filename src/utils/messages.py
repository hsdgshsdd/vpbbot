def get_message(key: str, **kwargs) -> str:
    """Получить отформатированное сообщение"""
    message = MESSAGES.get(key, "")
    
    if kwargs:
        message = message.format(**kwargs)
    
    return message


def get_faq_text() -> str:
    """Получить текст FAQ"""
    text = MESSAGES['help_general'] + "\n\n"
    
    for i, faq in enumerate(MESSAGES['faq'], 1):
        text += f"{i}️⃣ <b>{faq['question']}</b>\n"
        text += f"{faq['answer']}\n\n"
    
    return text
